/**
 * Borrowly domain model.
 *
 * Everything here is plain data so it can be persisted to localStorage
 * without any custom serialisation.
 */

export type Category =
  | "Tools"
  | "Kitchen"
  | "Home"
  | "Outdoors"
  | "Tech"
  | "Music"
  | "Games"
  | "Books"
  | "Crafts";

export type Owner = {
  id: string;
  name: string;
  /** Used for the monogram avatar fallback. */
  initials: string;
  floor: string;
  /** Human phrasing for proximity, e.g. "2 floors away". Never a precise address. */
  distance: string;
  rating: number;
  ratingCount: number;
  /** Completed, on-time returns. Not "items shared". */
  lends: number;
  memberSince: string;
  /** Only a small number of owners have a verified photo asset. */
  photo?: string;
  /** A short, human tip shown on the item page. */
  note?: string;
};

export type DateRange = {
  /** ISO `YYYY-MM-DD`. */
  from: string;
  to: string;
};

/** Where a listing came from: seeded demo data, or created in this prototype. */
export type ItemOrigin = "catalogue" | "user";

/**
 * How much of the owner's location is shown before a request is agreed.
 * The exact handoff spot is never part of this — see `handoffPlace`.
 */
export type LocationVisibility = "community" | "floor";

/** Free lending, or a fee charged per borrowing day. */
export type PricingType = "free" | "paid";

export type Pricing = {
  type: PricingType;
  /** Naira per borrowing day. Always `0` on a free listing. */
  dailyFee: number;
};

export type Deposit = {
  required: boolean;
  /** Refundable amount in naira. Always `0` when not required. */
  amount: number;
};

/**
 * The public, approximate location of a listing. Deliberately coarse: no
 * street or door number is ever part of it.
 */
export type ItemLocation = {
  city: string;
  neighbourhood: string;
  /** Named building or estate within the neighbourhood, when there is one. */
  community: string;
};

/** A manually chosen search area. `city: null` means anywhere. */
export type SearchArea = {
  city: string | null;
  neighbourhood: string | null;
};

/** How far from the chosen area to look. */
export type Reach = "neighbourhood" | "city" | "any";

export type Item = {
  id: string;
  name: string;
  category: Category;
  ownerId: string;
  /** Primary photo. Always `photos[0]`. */
  photo: string;
  /** Full gallery. Seeded items have a single photo. */
  photos: string[];
  condition: string;
  summary: string;
  description: string;
  accessories: string[];
  /** `null` means the owner has not filled this in yet. */
  maxDays: number | null;
  /** Kept private until a request is agreed. */
  handoffPlace: string;
  handoffNote: string;
  /** Handoff options the owner offers, e.g. "Lobby handover". */
  handoffPreferences: string[];
  availability: "available" | "unavailable";
  /** Shown when the item is unavailable, e.g. "Back in about 3 days". */
  unavailableNote?: string;
  bookedRanges: DateRange[];
  tags: string[];

  origin: ItemOrigin;
  location: ItemLocation;
  locationVisibility: LocationVisibility;
  pricing: Pricing;
  deposit: Deposit;
  /** ISO date the item is next lendable, or `null` for "right now". */
  availabilityFrom: string | null;
  /** Owner has paused lending without deleting the listing. */
  paused: boolean;
  createdAt: number;
  updatedAt: number;
};

export type RequestStatus = "pending" | "approved" | "declined" | "cancelled";

export type ExtensionRequest = {
  requestedAt: number;
  previousReturnDate: string;
  newReturnDate: string;
  status: "pending" | "approved" | "declined";
  decidedAt: number | null;
  reason: string;
};

export type HandoffAppointment = {
  /** `null` until the borrower picks a return slot. */
  date: string | null;
  /** One of the handoff slots, e.g. "6:30 PM". */
  slot: string | null;
  place: string;
  note: string;
};

export type ReturnCondition = "same" | "minor-wear" | "issue";

export type ReturnChecklist = {
  condition: ReturnCondition;
  /** Accessory labels the borrower confirmed are back in the bag. */
  accessories: string[];
  notes: string;
  completedAt: number;
};

export type Message = {
  id: string;
  /** `me` is the borrower using this prototype. */
  from: "me" | "owner";
  body: string;
  at: number;
  /** True when the text was generated by the prototype, not a real person. */
  simulated?: boolean;
};

export type Conversation = {
  ownerId: string;
  itemId: string;
  requestId: string | null;
  messages: Message[];
  unread: number;
};

export type IssueReport = {
  reportedAt: number;
  kind: "damaged" | "late" | "no-response" | "other";
  note: string;
};

export type BorrowRequest = {
  id: string;
  itemId: string;
  /**
   * For an outgoing request this is the neighbour lending to you. For an
   * incoming request it is the neighbour borrowing from you.
   */
  ownerId: string;
  /**
   * `outgoing` = you are borrowing. `incoming` = someone is borrowing from
   * your listing. Incoming requests are simulated — there is no
   * second account in this prototype.
   */
  direction: "outgoing" | "incoming";
  /** Set on incoming requests so the owner side has a name to show. */
  borrowerName: string | null;
  createdAt: number;
  /** ISO dates. */
  startDate: string;
  returnDate: string;
  /** Kept so extensions can be compared against the original agreement. */
  originalReturnDate: string;
  message: string;
  status: RequestStatus;
  decidedAt: number | null;
  declineReason: string | null;
  /** Set when the borrower confirms they have the item in hand. */
  collectedAt: number | null;
  /** Set when the borrower marks the item as handed back. */
  handedBackAt: number | null;
  /** Set when the owner confirms receipt. Only ever set by simulation. */
  confirmedAt: number | null;
  /**
   * Set when the borrower closes an unconfirmed return on their own side,
   * so a return the owner never answers does not sit open forever.
   */
  resolvedWithoutConfirmationAt: number | null;
  /** How many times the borrower has nudged an unconfirmed return. */
  nudges: number;
  handoff: {
    place: string;
    note: string;
    /** Free-text pickup arrangement the borrower proposed. */
    proposed: string;
  };
  returnHandoff: HandoffAppointment;
  returnChecklist: ReturnChecklist | null;
  extension: ExtensionRequest | null;
  issue: IssueReport | null;
};

/** The derived lifecycle state, computed from a request. */
export type LoanPhase =
  | "requested"
  | "approved"
  | "collected"
  | "overdue"
  | "return-pending"
  | "returned"
  | "declined"
  | "cancelled";

export type Draft = {
  startDate: string;
  returnDate: string;
  message: string;
  /** Set once the borrower has edited the message. */
  messageTouched: boolean;
};

/** How the Discover grid is ordered. */
export type ItemSort = "recommended" | "price-asc" | "price-desc" | "closest" | "newest";

/** One-tap narrowing chips above the grid. */
export type QuickFilter = "all" | "free" | "paid" | "cheap" | "available";

export type DiscoverFilters = {
  query: string;
  category: Category | "All";
  availableOnly: boolean;
  /** Manually chosen search area. */
  area: SearchArea;
  /** How far from `area` to include. */
  reach: Reach;
  sort: ItemSort;
  quick: QuickFilter;
};

export type Borrower = {
  name: string;
  initials: string;
  community: string;
  floor: string;
  memberSince: string;
  /** Where the signed-in borrower is browsing from. */
  location: ItemLocation;
};

export type PersistedState = {
  version: number;
  requests: BorrowRequest[];
  drafts: Record<string, Draft>;
  conversations: Conversation[];
  /** Listings the borrower published from this device. */
  listings: Item[];
};

/** Derived availability of a listing the borrower owns. */
export type ListingStatus = "available" | "scheduled" | "on-loan" | "paused";

